import { Schema } from "effect";
import { randomUUID } from "node:crypto";
import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { points } from "./core/points.ts";
import { elbowTable } from "./core/table.ts";
import { renderPage } from "./ui/render.ts";
import { snapshotSchema, validateSnapshot } from "./source/schema.ts";

await mkdir("data", { recursive: true });
const snapshots = (
  await Array.fromAsync(new Bun.Glob("aa-snapshot-*.json").scan("data"))
).toSorted();
const latest = snapshots.at(-1);
if (latest === undefined)
  throw new Error("No snapshot found in data/; run `bun run refresh` first");
const snapshot = validateSnapshot(
  Schema.decodeUnknownSync(snapshotSchema)(await Bun.file(`data/${latest}`).json()),
);
const data = points(snapshot);
if (data.length === 0) throw new Error("Snapshot contains no plottable configurations");
const template = await Bun.file("src/ui/template.html").text();
const bundle = await Bun.build({
  entrypoints: ["src/ui/browser.ts"],
  target: "browser",
  format: "iife",
  minify: true,
});
if (!bundle.success || !bundle.outputs[0]) throw new Error("Could not bundle chart UI");
const app = await bundle.outputs[0].text();
const date = snapshot.source.fetched_at.slice(0, 10);
const html = renderPage(template, app, data, date);
const elbows = `_Generated by \`bun run build\` from the ${date} snapshot._\n\n${elbowTable(data)}\n`;
await mkdir("dist", { recursive: true });
const temporaryHtml = `dist/.chart-${randomUUID()}.tmp`;
const temporaryElbows = `dist/.elbows-${randomUUID()}.tmp`;
try {
  await writeFile(temporaryHtml, html, { flag: "wx" });
  await writeFile(temporaryElbows, elbows, { flag: "wx" });
  await rename(temporaryHtml, "dist/opifex.html");
  await rename(temporaryElbows, "dist/elbows.md");
} finally {
  await rm(temporaryHtml, { force: true });
  await rm(temporaryElbows, { force: true });
}
console.log(
  `Built ${data.length} configurations from ${latest} into dist/opifex.html and dist/elbows.md`,
);
